const GENERATED_MARKERS = [
  "@generated",
  "auto-generated",
  "autogenerated",
  "do not edit",
  "this file was generated",
  "generated by",
  "codegen",
  "// regenerate",
];

export function looksGenerated(text: string): boolean {
  const head = text.slice(0, 1200).toLowerCase();
  return GENERATED_MARKERS.some((marker) => head.includes(marker.toLowerCase()));
}

