export function isEnvFileName(name: string): boolean {
  return (
    name === ".env" ||
    name.startsWith(".env.") ||
    name.endsWith(".env") ||
    name.includes(".env.")
  );
}

export function classifyFile(rel: string): IndexedFile["kind"] {
  const base = path.basename(rel);
  const ext = path.extname(rel).toLowerCase();
  if (base === "package-lock.json" || base === "pnpm-lock.yaml" || base === "yarn.lock") {
    return "lock";
  }
  if (isEnvFileName(base)) return "env";
  if (CONFIG_BASENAMES.has(base)) return "config";
  if (CSS_EXTS.has(ext)) return "css";
  if (HTML_EXTS.has(ext)) return "html";
  if (SOURCE_EXTS.has(ext)) {
    if (isTestPattern(rel)) return "test";
    return "source";
  }
  if (ext === ".json") return "json";
  if ([".md", ".mdx", ".txt", ".rst"].includes(ext)) return "doc";
  if (ext === ".lock") return "other";
  return "other";
}

/**
 * Determines whether a path is a test file based on conventional naming.
 * Test runners (jest/vitest/playwright) discover these automatically, so they
 * act as entry points for the reference graph.
 */
export function isTestPattern(rel: string): boolean {
  const base = path.basename(rel);
  return (
    /\.(test|spec)\.(ts|tsx|js|jsx|mjs|cjs|mts|cts)$/.test(base) ||
    /(^|\/)(__tests__|tests?|e2e|integration|specs?|cypress|playwright)(\/|$)/.test(rel) ||
    /\.e2e\./.test(base)
  );
}

export function isTestUtilPattern(rel: string): boolean {
  return (
    /(^|\/)(__tests__|tests?|e2e|test-utils?|__mocks__|fixtures?|mocks?)(\/|$)/.test(rel) ||
    /\btest(ing)?-[a-z-]+\.(ts|tsx|js|jsx)$/.test(path.basename(rel))
  );
}

export function isGeneratedFile(rel: string, text: string): boolean {
  return looksGenerated(text);
}

export async function indexFiles(root: string, matcher: IgnoreMatcher): Promise<FileIndex> {
  const rels = walkFiles(root, { matcher });
  const files: IndexedFile[] = [];
  const texts = new Map<string, string>();
  for (const rel of rels) {
    const abs = path.join(root, rel);
    let stat: fs.Stats;
    let text: string;
    try {
      stat = fs.statSync(abs);
      text = fs.readFileSync(abs, "utf8");
    } catch {
      continue;
    }
    const ext = path.extname(rel).toLowerCase();
    const kind = classifyFile(rel);
    const generated = SOURCE_EXTS.has(ext) ? isGeneratedFile(rel, text) : false;
    files.push({
      abs,
      rel,
      ext,
      kind,
      lines: countLines(text),
      size: stat.size,
      generated,
    });
    texts.set(abs, text);
  }
  return { files, texts };
}